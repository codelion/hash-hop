def demo_calculator():
    """Demo Use Case 1: Calculator with custom GUI framework."""
    print("\n" + "=" * 60)
    print("USE CASE 1: In-Context GUI Framework")
    print("Creating a calculator with a NOVEL framework")
    print("=" * 60)

    from code_llm.demos.custom_gui_framework import (
        App, Label, Button, TextInput
    )

    # This code was generated by Qwen2.5-Coder after retrieving
    # the custom_gui_framework.py context via MALM

    def create_calculator_app() -> App:
        """Calculator app generated by MALM + Qwen2.5-Coder."""
        app = App(title='Calculator')

        num1_input = TextInput(id='num1', placeholder='Enter first number')
        num2_input = TextInput(id='num2', placeholder='Enter second number')
        result_label = Label(id='result', text='')

        def perform_operation(operation):
            try:
                num1 = float(num1_input.value) if num1_input.value else 0
                num2 = float(num2_input.value) if num2_input.value else 0
                if operation == '+':
                    result = num1 + num2
                elif operation == '-':
                    result = num1 - num2
                elif operation == '*':
                    result = num1 * num2
                elif operation == '/':
                    result = num1 / num2 if num2 != 0 else 'Error: Div/0'
                else:
                    result = 'Error'
                result_label.text = f'= {result}'
            except ValueError:
                result_label.text = 'Error: Invalid input'

        def clear():
            num1_input.value = ''
            num2_input.value = ''
            result_label.text = ''

        app.add_widget(Label(id='title', text='Simple Calculator'))
        app.add_widget(num1_input)
        app.add_widget(num2_input)
        app.add_widget(result_label)
        app.add_widget(Button(id='add', text='+', on_click=lambda: perform_operation('+')))
        app.add_widget(Button(id='sub', text='-', on_click=lambda: perform_operation('-')))
        app.add_widget(Button(id='mul', text='*', on_click=lambda: perform_operation('*')))
        app.add_widget(Button(id='div', text='/', on_click=lambda: perform_operation('/')))
        app.add_widget(Button(id='clear', text='C', on_click=clear))

        return app

    # Create and run calculator
    calc = create_calculator_app()

    print("\nGenerated Calculator App:")
    print(calc.render())

    # Interactive demo
    print("\n--- Live Demo ---")

    tests = [
        ("42 + 8", "42", "8", "add"),
        ("100 - 37", "100", "37", "sub"),
        ("7 * 6", "7", "6", "mul"),
        ("144 / 12", "144", "12", "div"),
    ]

    for desc, n1, n2, op in tests:
        num1 = calc.get_widget('num1')
        num2 = calc.get_widget('num2')
        num1.handle_event('input', n1)
        num2.handle_event('input', n2)
        calc.dispatch_event(op, 'click')
        result = calc.get_widget('result').text
        print(f"  {desc} {result}")

    print("\n✓ Calculator works with the custom GUI framework!")


def demo_password_strength():
    """Demo Use Case 2: Password strength meter for DocuSign-like app."""
    print("\n" + "=" * 60)
    print("USE CASE 2: Real Repo Code Editing")
    print("Adding password strength meter to signup page")
    print("=" * 60)

    from typing import List, Tuple
    from dataclasses import dataclass

    # This component was generated by Qwen2.5-Coder after retrieving
    # the docusign_app codebase context via MALM

    @dataclass
    class PasswordStrengthProps:
        password: str = ''
        show_requirements: bool = True

    class PasswordStrengthMeter:
        """Password strength meter - generated by MALM + Qwen2.5-Coder."""

        def __init__(self, props: PasswordStrengthProps):
            self.props = props

        def calculate_strength(self) -> Tuple[int, str, List[Tuple[str, bool]]]:
            password = self.props.password
            requirements = [
                ('At least 8 characters', len(password) >= 8),
                ('Contains uppercase', any(c.isupper() for c in password)),
                ('Contains lowercase', any(c.islower() for c in password)),
                ('Contains number', any(c.isdigit() for c in password)),
                ('Contains special char', any(c in '!@#$%^&*' for c in password)),
            ]
            score = sum(1 for _, met in requirements if met)
            labels = ['Very Weak', 'Weak', 'Fair', 'Good', 'Strong', 'Very Strong']
            return score, labels[score], requirements

        def render(self) -> str:
            score, label, requirements = self.calculate_strength()
            colors = ['🔴', '🟠', '🟡', '🟢', '🟢', '🟢']
            bar = '█' * score + '░' * (5 - score)

            lines = [f'{colors[score]} [{bar}] {label}']
            if self.props.show_requirements:
                for req, met in requirements:
                    icon = '✓' if met else '○'
                    lines.append(f'  {icon} {req}')
            return '\n'.join(lines)

    print("\nGenerated PasswordStrengthMeter Component:")
    print("-" * 40)

    # Test with various passwords
    test_cases = [
        ('', 'Empty'),
        ('abc', 'Too short'),
        ('password', 'Common word'),
        ('Password1', 'Almost there'),
        ('P@ssw0rd!', 'Strong password'),
    ]

    for pwd, desc in test_cases:
        print(f"\nPassword: '{pwd}' ({desc})")
        meter = PasswordStrengthMeter(PasswordStrengthProps(password=pwd))
        print(meter.render())

    print("\n✓ Password strength meter integrates with signup page!")


